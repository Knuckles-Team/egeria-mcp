class _Resp:
    def __init__(self, items: list[dict]) -> None:
        self.status_code = 200
        self._items = items


class FakeReconcileApi:
    """No-network fake: serves ``_paginated_search`` by literal searchString
    term, records every write call, and backs ``lineage()``/idempotency off
    the same ``link_data_flow`` calls it records — exactly like the real
    client's lineage graph would reflect a prior write.
    """

    def __init__(self, catalog=None, enable_write=True, governance=None):
        self.enable_write = enable_write
        self._catalog = catalog if catalog is not None else _build_catalog()
        self._lineage: dict[str, set[str]] = {}
        self.link_calls: list[tuple[str, str, str]] = []
        self._collections: dict[str, str] = {}
        self.create_collection_calls: list[str] = []
        self._governance: dict[str, dict] = dict(governance or {})
        self.set_confidentiality_calls: list[tuple[str, int]] = []
        self._last_term: str | None = None

    def _bearer(self) -> str:
        return "tok"

    def _omvs(self, service: str, sub_path: str) -> str:
        return f"https://fake.invalid/{service}/{sub_path}"

    def _http(self):
        return self

    def post(self, url, headers=None, content=None):
        body = _json.loads(content)
        self._last_term = body["searchString"]
        return _Resp(self._catalog.get(self._last_term, []))

    def _elements(self, resp: _Resp) -> list[dict]:
        return resp._items

    def lineage(self, guid: str, direction: str = "both", depth: int = 2) -> dict:
        edges = self._lineage.get(guid, set())
        return {
            "lineageLinkage": [
                {"relatedElement": {"elementHeader": {"guid": g}}} for g in edges
            ]
        }

    def link_data_flow(self, source_guid: str, target_guid: str, label: str = ""):
        self.link_calls.append((source_guid, target_guid, label))
        self._lineage.setdefault(source_guid, set()).add(target_guid)
        return {"guid": f"edge-{len(self.link_calls)}"}

    def create_collection(self, name: str, description: str = "", category: str = ""):
        self.create_collection_calls.append(name)
        if name not in self._collections:
            self._collections[name] = f"col-{len(self._collections) + 1}"
        return {"guid": self._collections[name]}

    def governance_for(self, guid: str) -> dict:
        return self._governance.get(guid, {})

    def set_confidentiality(self, guid: str, level: int):
        self.set_confidentiality_calls.append((guid, level))
        self._governance.setdefault(guid, {})["confidentialityLevel"] = level
        return {"ok": True}


_GOVERNANCE = {
    "s1": {"confidentialityLevel": 1},
    "d1": {"confidentialityLevel": 3},
    "d2": {"confidentialityLevel": 5},
}


def _fresh_governance() -> dict[str, dict]:
    # Deep-enough copy: FakeReconcileApi.set_confidentiality mutates the
    # per-guid dict in place, so a shallow `dict(_GOVERNANCE)` would leak
    # mutations across tests via the shared inner dict objects.
    return {guid: dict(levels) for guid, levels in _GOVERNANCE.items()}


def _run() -> tuple[dict, FakeReconcileApi]:
    api = FakeReconcileApi(governance=_fresh_governance())
    return reconcile(api), api


