def test_bug_monitoring_precedence_last_writer_wins_route_over_store_svc_node():
    """BUG-1 (part a): three DIFFERENT asset kinds share the core name
    "shared1" (DataStore::shared1 / Service::shared1 / Node::shared1 /
    Route::shared1). ``_pattern_monitoring``'s ``targets_by_name`` is built by
    ``**``-merging ``store_by_name``, ``svc_by_name``, a Node:: index, and a
    Route:: index IN THAT ORDER — a plain dict update, so the LAST dict
    merged silently wins any name collision with no signal that a collision
    even occurred. Monitor::shared1 ends up wired to the ROUTE, not the
    store/service/node that likely hosts the thing actually being monitored.
    """
    report, api = _run()
    m1_targets = [tg for sg, tg, _label in api.link_calls if sg == "m1"]
    assert m1_targets == ["rt1"]  # Route::shared1 — NOT s2 (store) or sv2 (service) or n3 (node)


def test_bug_cmdb_identity_precedence_disagrees_with_monitoring_for_same_collision():
    """BUG-1 (part b): the SAME "shared1" collision resolves to a DIFFERENT
    winner in ``_pattern_cmdb_identity`` (merge order store -> node -> svc,
    svc wins) than in ``_pattern_monitoring`` (merge order store -> svc ->
    node -> route, route wins) — proving the "winner" is an accident of each
    block's copy-pasted merge-literal order, not a deliberate priority rule.
    """
    report, api = _run()
    ci3_targets = [tg for sg, tg, _label in api.link_calls if sg == "ci3"]
    assert ci3_targets == ["sv2"]  # Service::shared1 — a DIFFERENT winner than monitoring's route


def test_bug_ea_realization_precedence_repo_silently_overwrites_service():
    """BUG-1 (part c): the same defect class in ``_pattern_ea_realization``'s
    ``real_by_name`` (built via services.update() -> stores.update() ->
    repos.update(); Service::worker and Repository::org/worker share core
    name "worker") — the LAST ``.update()`` (repos) wins, so
    FactSheet::Y (displayName "worker") realizes the REPOSITORY, not the
    service most likely intended by an EA element named after a running
    workload.
    """
    report, api = _run()
    ea2_targets = [tg for sg, tg, _label in api.link_calls if sg == "ea2"]
    assert ea2_targets == ["r4"]  # Repository::org/worker — NOT sv4 (Service::worker)


def test_bug_confidentiality_propagation_blind_to_source_store_hosting_edges():
    """BUG-2: ``_pattern_confidentiality_propagation`` (P10) re-derives its own
    "which store hosts this dataset" answer purely from the dataset's
    qualifiedName (``Dataset::<store>::...``) — the SAME rule as P4
    (dataset-store) — instead of consulting the "hosts" edges P4 AND P11
    (source-store) actually created. Dataset::telemetry.raw (d2,
    confidentialityLevel=5) IS hosted by DataStore::kafka per the
    source-store pattern (see source-store link above), but its
    qualifiedName has only one "::" so P10 never even considers it: the
    store ends up raised only to level 3 (from d1), never to 5, silently
    violating the module docstring's own claim ("a store that hosts
    Confidential data is raised to at least that level").
    """
    report, api = _run()
    assert api.set_confidentiality_calls == [("s1", 3)]  # never (s1, 5)
    assert report["confidentiality-propagation"]["links"] == 1  # d2 never counted
