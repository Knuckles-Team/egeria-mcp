def test_reconcile_negative_cases_produce_no_links():
    """m3/nomatch, ci2/orphan, cl2/orphan, rt3/orphan, dsc2/orphan never
    appear as the source of ANY recorded link_data_flow call."""
    _report, api = _run()
    orphan_guids = {"m3", "ci2", "cl2", "rt3", "dsc2"}
    sources_used = {sg for sg, _tg, _label in api.link_calls}
    assert not (orphan_guids & sources_used)


def test_reconcile_rerun_is_idempotent_no_duplicate_links():
    api = FakeReconcileApi(governance=_fresh_governance())
    first = reconcile(api)
    second = reconcile(api)
    assert first["summary"]["total_links"] == 26
    assert second["summary"]["total_links"] == 0
    assert second["summary"]["confidentiality-propagation"] == 0
    # capability-cohort's collection lookup is itself idempotent (same name ->
    # same guid), so the cohort's own group-links are idempotent too.
    assert api.create_collection_calls == [
        "Capability vcs",
        "Capability enterprise-architecture",
        "Capability vcs",
        "Capability enterprise-architecture",
    ]


