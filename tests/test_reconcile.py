"""CXA-FL-EGERIAMCP-01: characterization tests for ``reconcile`` (CCN 108).

``reconcile`` weaves the 34 harvest layers' independently-catalogued assets into
one graph via ~15 deterministic pattern matchers (see ``PATTERNS``), each
creating labelled ``DataFlow`` edges through the shared ``link()`` closure, plus
a confidentiality-propagation pass that is NOT gated through ``link()``.

These tests pin the CURRENT behaviour of the unmodified ``main``-branch
function — including its bugs — against a no-network fake Egeria client
(``FakeReconcileApi``). The fixture (``_build_catalog``) is a small but
deliberately cross-linked asset graph designed to exercise every one of the 15
patterns at least once (a positive AND, where cheap, a negative/no-match case),
plus THREE call sites that share the literal core name ``"shared1"`` across
Node/DataStore/Service/Route — this collision is what reveals BUG-1 and BUG-2
below (see the ``test_bug_*`` tests and the lane report).

Do not edit this file in commit 2 (the refactor commit) — it must stay
byte-identical; that is the two-commit discipline's proof that behaviour did
not change under the extract-method refactor.
"""

